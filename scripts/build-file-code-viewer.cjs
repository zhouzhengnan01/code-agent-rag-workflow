/* Rebuild the offline bundle from the unpacked official prismjs@1.30.0 npm package.
 * Usage: node scripts/build-file-code-viewer.cjs /path/to/unpacked/package
 * This script never installs or executes dependency lifecycle scripts.
 */
'use strict';
const fs = require('node:fs');
const path = require('node:path');
const packageDir = path.resolve(process.argv[2] || 'node_modules/prismjs');
const pkg = JSON.parse(fs.readFileSync(path.join(packageDir, 'package.json'), 'utf8'));
if (pkg.name !== 'prismjs' || pkg.version !== '1.30.0') throw new Error('Expected official prismjs@1.30.0 package');
const components = JSON.parse(fs.readFileSync(path.join(packageDir, 'components.json'), 'utf8')).languages;
const selected = ['markup', 'css', 'javascript', 'python', 'typescript', 'jsx', 'tsx', 'json', 'yaml', 'bash', 'powershell', 'sql', 'markdown', 'toml', 'c', 'cpp', 'java', 'go', 'rust'];
const ordered = [];
const seen = new Set();
function add(name) {
  if (seen.has(name)) return;
  seen.add(name);
  for (const required of [].concat(components[name].require || [])) add(required);
  ordered.push(name);
}
selected.forEach(add);
const output = path.join(__dirname, '../web/vendor/prism');
fs.mkdirSync(output, { recursive: true });
const files = ['core', ...ordered].map(name => fs.readFileSync(path.join(packageDir, 'components', `prism-${name}.min.js`), 'utf8'));
fs.writeFileSync(path.join(output, 'prism.js'), '/* PrismJS 1.30.0, MIT license; see LICENSE. Generated by scripts/build-file-code-viewer.cjs. */\n' +
  '/* Disable automatic DOM highlighting: file previews are explicitly rendered. */\n' +
  'var Prism = { manual: true, disableWorkerMessageHandler: true };\n' +
  'if (typeof window !== "undefined") window.Prism = Prism;\n' + files.join('\n;\n') + '\n');
fs.copyFileSync(path.join(packageDir, 'LICENSE'), path.join(output, 'LICENSE'));
console.log(`Bundled PrismJS ${pkg.version}: ${ordered.join(', ')}`);
